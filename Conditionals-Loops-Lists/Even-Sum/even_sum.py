# sum of even numbers 1-50 through for loop
x=0
for i in range(1,51):
    if i % 2 == 0:
         x=x+i
print("The sum of even numbers from 1 to 50 is", x)

# sum of even numbers 1-50 through while loop
x = 0
i = 1
while i <= 50:
     if i % 2 == 0:
         x=x+i
     i+=1
print("The sum of even numbers from 1 to 50 is", x)


 
 
 
    